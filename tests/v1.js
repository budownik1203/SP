const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
  const errs = [];
  p.on('pageerror', e => errs.push('PAGEERR ' + e.message + '\n' + e.stack));
  p.on('console', m => { if (m.type() === 'error' && !m.text().includes('ERR_TUNNEL')) errs.push(m.text()); });
  await p.goto('file:///home/claude/sztandary/dist/sztandary.html');
  await p.waitForTimeout(800);
  await p.click('text=Nowa gra'); await p.waitForTimeout(200);
  await p.click('text=Kapłan wojownik'); await p.waitForTimeout(200);
  await p.screenshot({ path: 'v_creator.png' });
  for (let i = 0; i < 4; i++) await p.click('#ui button[data-a="next"]'); await p.uncheck('#ui input[data-in="prologue"]'); await p.click('text=Ruszaj w świat'); await p.waitForTimeout(1300); await p.waitForTimeout(600);
  await p.screenshot({ path: 'v_map.png' });
  await p.keyboard.press('KeyC'); await p.waitForTimeout(300);
  await p.click('button.ttab:has-text("Wiara")'); await p.waitForTimeout(200);
  await p.click('button.node:has-text("Smite")'); await p.waitForTimeout(200);
  await p.click('text=Odblokuj (1 punkt)'); await p.waitForTimeout(200);
  await p.screenshot({ path: 'v_char.png' });
  await p.click('button.ttab:has-text("Oręż")'); await p.waitForTimeout(200);
  await p.screenshot({ path: 'v_char2.png' });
  await p.keyboard.press('KeyC'); await p.waitForTimeout(200);
  await p.evaluate(() => { const w = window.__game().WORLD; const pp = w.parties.find(x=>x.kind==='player'); pp.troops.push({type:'a_militia',n:6,wounded:1,xp:900},{type:'a_knight',n:2,wounded:0,xp:0}); });
  await p.keyboard.press('KeyP'); await p.waitForTimeout(300);
  await p.click('button.urow:has-text("Milicjant")'); await p.waitForTimeout(200);
  await p.screenshot({ path: 'v_party.png' });
  await p.keyboard.press('KeyP'); await p.waitForTimeout(200);
  await p.evaluate(() => { const T = window.__T; const w = window.__game().WORLD; T.enterSettlement(w.settlements[0]); });
  await p.click('button.tab:has-text("Rekrutacja")'); await p.waitForTimeout(300);
  await p.screenshot({ path: 'v_recruit.png' });
  await p.keyboard.press('Escape');
  await p.evaluate(() => { const T = window.__T; const w = window.__game().WORLD; const l = w.parties.find(x=>x.kind==='lord' && x.faction===1); T.meetParty(l, false); });
  await p.waitForTimeout(900); await p.screenshot({ path: 'v_meet.png' });
  await p.keyboard.press('Digit1'); await p.waitForTimeout(900); await p.screenshot({ path: 'v_talk.png' });
  console.log(errs.join('\n'));
  await b.close();
})();
